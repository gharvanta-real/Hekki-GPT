@router.get("")
async def get_workspace(
    path: str = Query("", description="Relative path within workspace"),
    project_path: str = Query("", description="Absolute path of active project")
):
    """Lists files and directories inside the specified relative workspace path."""
    if project_path and Path(project_path).is_absolute():
        workspace_dir = Path(project_path).resolve()
        workspace_dir.mkdir(parents=True, exist_ok=True)
    else:
        workspace_dir = get_workspace_dir()
    
    # Resolve target directory securely
    try:
        if path:
            target_dir = (workspace_dir / path).resolve()
        else:
            target_dir = workspace_dir
        
        # Security Guard: Prevent directory traversal outside data/workspace
        if not target_dir.is_relative_to(workspace_dir):
            raise HTTPException(status_code=403, detail="Access denied: outside workspace scope.")
            
        if not target_dir.exists():
            raise HTTPException(status_code=404, detail="Directory not found.")
        if not target_dir.is_dir():
            raise HTTPException(status_code=400, detail="Target path is not a directory.")
            
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=400, detail=f"Invalid path configuration: {exc}")

    items = []
    try:
        for entry in sorted(target_dir.iterdir(), key=lambda e: (not e.is_dir(), e.name.lower())):
            # Skip hidden files
            if entry.name.startswith("."):
                continue
                
            is_dir = entry.is_dir()
            stat = entry.stat()
            
            # Format relative path with forward slashes for web consistency
            rel_path = str(entry.relative_to(workspace_dir)).replace("\\", "/")
            
            items.append({
                "name": entry.name,
                "is_dir": is_dir,
                "size_bytes": stat.st_size if not is_dir else 0,
                "modified_time": stat.st_mtime,
                "relative_path": rel_path
            })
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to scan directory: {exc}")

    return {
        "current_path": path.replace("\\", "/"),
        "items": items
    }


@router.get("/list-projects")
async def list_projects():
    """Lists all projects/workspaces inside the workspace root folder."""
    workspace_dir = get_workspace_dir()
    try:
        projects = []
        for entry in workspace_dir.iterdir():
            if entry.is_dir() and not entry.name.startswith("."):
                stat = entry.stat()
                projects.append({
                    "name": entry.name,
                    "path": str(entry.resolve()),
                    "modified_time": stat.st_mtime
                })
        # Sort by modified time descending (newest first)
        projects.sort(key=lambda p: p["modified_time"], reverse=True)
        return {"projects": projects}
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


class WorkspaceSetRequest(BaseModel):
    project_id: str
    project_path: str | None = None


@router.post("/set")
async def set_active_workspace(req: WorkspaceSetRequest):
    """Sets the active project workspace context, initializes and seeds directories."""
    try:
        settings = get_settings()
        project_id = req.project_id
        project_path = req.project_path
        
        # If project_path is empty or not absolute, resolve to local sandbox
        if not project_path or not Path(project_path).is_absolute():
            proj_dir = (settings.mariano_data_dir / "workspace" / project_id).resolve()
        else:
            proj_dir = Path(project_path).resolve()
            
        # Ensure workspace folder exists
        proj_dir.mkdir(parents=True, exist_ok=True)
        seed_default_workspace(proj_dir)
        
        # Set transient project context in PathGuard
        PathGuard.set_active_project(project_id, project_path=str(proj_dir))
        
        return {
            "status": "success",
            "project_id": project_id,
            "project_path": str(proj_dir),
            "exists": proj_dir.exists()
        }
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


