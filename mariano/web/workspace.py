async def _read_file_content(file_path: str, project_path: str = "") -> dict:
    """Safely reads content of a text file inside the workspace."""
    if project_path and Path(project_path).is_absolute():
        workspace_dir = Path(project_path).resolve()
    else:
        workspace_dir = get_workspace_dir()
    
    try:
        target_file = (workspace_dir / file_path).resolve()
        
        # Security Guard: Prevent directory traversal outside the workspace scope
        if not target_file.is_relative_to(workspace_dir):
            raise HTTPException(status_code=403, detail="Access denied: outside workspace scope.")
            
        if not target_file.exists():
            raise HTTPException(status_code=404, detail="File not found.")
        if not target_file.is_file():
            raise HTTPException(status_code=400, detail="Target path is not a file.")
            
        # Read text content safely (limit 2MB)
        file_size = target_file.stat().st_size
        if file_size > 2 * 1024 * 1024:
            raise HTTPException(status_code=413, detail="File too large to preview (max 2MB).")
        
        content = target_file.read_text(encoding="utf-8", errors="replace")
        return {"path": file_path, "name": target_file.name, "content": content}
        
    except HTTPException:
        raise
    except Exception as exc:
        raise HTTPException(status_code=500, detail=f"Failed to read file: {exc}")


@router.get("/render/{file_path:path}")
async def render_file_path(file_path: str):
    """Serve files by path parameter to support relative resource loading in iframe."""
    try:
        # Standardize drive letter path capture (e.g., "D/web-test/..." -> "D:/web-test/...")
        if len(file_path) > 2 and file_path[1] == '/' and file_path[0].isalpha():
            file_path = file_path[0] + ":" + file_path[1:]
            
        raw_path = Path(file_path)
        antigravity_path = Path("C:/Users/anshu/.gemini/antigravity").resolve()
        if raw_path.is_absolute() and raw_path.resolve().is_relative_to(antigravity_path):
            resolved_path = raw_path.resolve()
        else:
            resolved_path = PathGuard.secure_path(file_path)
            
        if not resolved_path.is_file():
            raise HTTPException(status_code=400, detail="Path is not a file")
            
        # Determine media type for preview assets to avoid browser MIME type enforcement blocking
        media_type = None
        ext = resolved_path.suffix.lower()
        if ext == ".css":
            media_type = "text/css"
        elif ext in (".js", ".mjs"):
            media_type = "application/javascript"
        elif ext == ".svg":
            media_type = "image/svg+xml"
            
        return FileResponse(resolved_path, media_type=media_type)
    except PermissionError as exc:
        raise HTTPException(status_code=403, detail=str(exc))
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


