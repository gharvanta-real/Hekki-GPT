def seed_default_workspace(workspace_dir: Path) -> None:
    """Creates the default folder structure only if workspace is brand new (empty)."""
    existing = [e for e in workspace_dir.iterdir() if not e.name.startswith(".")]
    if existing:
        return  # Already has content — don't overwrite
    
    for folder_name, files in _DEFAULT_FOLDERS.items():
        folder_path = workspace_dir / folder_name
        folder_path.mkdir(parents=True, exist_ok=True)
        for file_name, content in files.items():
            file_path = folder_path / file_name
            if not file_path.exists():
                file_path.write_text(content, encoding="utf-8")


# ── Helpers ──────────────────────────────────────────────────────────────────
def get_workspace_dir() -> Path:
    """Helper to resolve workspace directory path securely."""
    settings = get_settings()
    workspace_dir = settings.mariano_data_dir / "workspace"
    workspace_dir.mkdir(parents=True, exist_ok=True)
    resolved = workspace_dir.resolve()
    seed_default_workspace(resolved)
    return resolved


